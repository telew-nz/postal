# frozen_string_literal: true

# Renders per-domain spam rules into rspamd multimap map files and a generated
# rspamd config fragment.
#
# This runs inside the bootstrap container, where the app code is mounted, so it
# reads DomainSpamRule directly from the main database. It is driven by
# `./deploy.sh rspamd` on the host.
#
# Output: for each domain with enabled rules, a map file is written under the
# rspamd config directory (mounted into the rspamd container), plus a
# local.d/multimap-generated.conf fragment that references those maps.
#
#   - blocklist entries become a map matched on the envelope sender, action
#     "reject" by default (so the message is refused at SMTP time).
#   - allowlist entries become a map that lowers the score / whitelists.
#
# The maps are keyed per domain so independent client domains do not share
# allow/block decisions.

require "fileutils"

work_dir = ENV.fetch("RSPAMD_RENDER_DIR", "/config/rspamd")
maps_dir = File.join(work_dir, "maps")
# rspamd's local.d/ directory only merges a file whose name matches a base
# config file (modules.d/multimap.conf). A custom filename like
# multimap-generated.conf is ignored, so the module never sees our rules. It
# must be local.d/multimap.conf.
fragment = File.join(work_dir, "local.d", "multimap.conf")

# The path to the map directory as seen by the rspamd container. The renderer
# runs in the bootstrap container, where work_dir is /rspamd-config; but the
# generated fragment is consumed by the rspamd container, where the maps are
# mounted at /etc/rspamd/maps. If we wrote the bootstrap-side path into the
# fragment, rspamd would fail to load the map and the blocklist/allowlist
# symbols would never fire.
maps_container_dir = ENV.fetch("RSPAMD_MAP_PATH", "/etc/rspamd/maps")

FileUtils.mkdir_p(maps_dir)
FileUtils.mkdir_p(File.join(work_dir, "local.d"))

# Collect rules grouped by domain name, only enabled ones.
grouped = Hash.new { |h, k| h[k] = { allowlist: [], blocklist: [] } }

DomainSpamRule.where(enabled: true).includes(:domain).find_each do |rule|
  next unless rule.domain

  name = rule.domain.name
  if rule.allowlist?
    grouped[name][:allowlist] << rule.value.to_s.downcase
  else
    grouped[name][:blocklist] << rule.value.to_s.downcase
  end
end

allow_entries = []
block_entries = []

grouped.sort.each do |domain, lists|
  # A domain-specific allowlist map. Matched on sender (From/envelope). A
  # matching sender is strongly whitelisted.
  unless lists[:allowlist].empty?
    path = File.join(maps_dir, "#{domain}.allowlist.map")
    File.write(path, lists[:allowlist].uniq.join("\n") + "\n")
    allow_entries << {
      "name" => "ALLOWLIST_#{domain.gsub(/[^A-Za-z0-9_]/, '_')}",
      "type" => "from_smtp",
      "map" => File.join(maps_container_dir, "#{domain}.allowlist.map"),
      "score" => -15.0,
      "description" => "Allowlisted sender for #{domain}"
    }
  end

  unless lists[:blocklist].empty?
    path = File.join(maps_dir, "#{domain}.blocklist.map")
    File.write(path, lists[:blocklist].uniq.join("\n") + "\n")
    block_entries << {
      "name" => "BLOCKLIST_#{domain.gsub(/[^A-Za-z0-9_]/, '_')}",
      "type" => "from_smtp",
      "map" => File.join(maps_container_dir, "#{domain}.blocklist.map"),
      # Postal does not act on rspamd's symbol "action"; it only reads the
      # returned score against the server's spam_failure_threshold. A high
      # score here is what turns the blocklist into a hard fail (the message is
      # dropped in fail_if_spam), so it must exceed that threshold. The
      # "reject" action is kept for humans / other consumers of the map.
      "score" => 100.0,
      "action" => "reject",
      "description" => "Blocklisted sender for #{domain}"
    }
  end
end

# rspamd multimap config fragment.
io = StringIO.new
io.puts("# Generated by ./deploy.sh rspamd. Do not edit by hand.")
io.puts("# One multimap entry per domain per direction.")
io.puts("")

io.puts("multimap {")
(block_entries + allow_entries).each do |entry|
  io.puts("  #{entry['name']} {")
  io.puts("    type = \"#{entry['type']}\";")
  io.puts("    map = \"#{entry['map']}\";")
  io.puts("    score = #{entry['score']};") if entry["score"]
  io.puts("    action = \"#{entry['action']}\";") if entry["action"]
  io.puts("    description = \"#{entry['description']}\";")
  io.puts("  }")
end
io.puts("}")

File.write(fragment, io.string)

puts "rendered #{grouped.size} domain(s), #{block_entries.size} blocklist map(s), #{allow_entries.size} allowlist map(s)"
