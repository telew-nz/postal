# frozen_string_literal: true

# Writes the rspamd multimap fragment which `./deploy.sh rspamd` mounts into the
# rspamd container, and removes the per-domain sender maps an earlier version of
# this script rendered.
#
# Per-domain spam rules are NOT rendered into rspamd. rspamd is one scanner for
# the whole installation: a sender map in it matches that sender for every
# server's mail, so one tenant's blocklist rejected the sender for all of them
# and one tenant's allowlist whitelisted the sender for all of them. It also
# only returns a score, so a blocklisted sender was hard-failed whatever action
# its rule asked for.
#
# The rules are applied by Postal itself, in
# app/lib/message_dequeuer/incoming_message_processor.rb, where the receiving
# server and domain are known and the rule's action is honoured. rspamd is left
# to do what it is for: scoring a message.
#
# The fragment is still written, empty, because docker-compose.yml binds it into
# the container as a file and a bind mount needs the file to exist.

require "fileutils"

work_dir = ENV.fetch("RSPAMD_RENDER_DIR", "/config/rspamd")
maps_dir = File.join(work_dir, "maps")
# rspamd's local.d/ directory only merges a file whose name matches a base
# config file (modules.d/multimap.conf), so the fragment keeps that name.
fragment = File.join(work_dir, "local.d", "multimap.conf")

FileUtils.mkdir_p(maps_dir)
FileUtils.mkdir_p(File.join(work_dir, "local.d"))

stale = Dir[File.join(maps_dir, "*.allowlist.map")] + Dir[File.join(maps_dir, "*.blocklist.map")]
stale.each { |path| File.delete(path) }

File.write(fragment, <<~CONF)
  # Generated by ./deploy.sh rspamd. Do not edit by hand.
  # Deliberately empty: per-domain spam rules are applied by Postal, not by
  # rspamd. See deploy/lib/render_rspamd.rb for why.
CONF

puts "wrote an empty multimap fragment; removed #{stale.size} sender map(s) rendered by an earlier version"
